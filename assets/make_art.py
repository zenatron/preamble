"""Builds assets/icon.svg and assets/banner.svg from the README's logo.

Each terminal cell is one pixel wide and two tall (a half block is one square
pixel), so the glyphs below are drawn exactly as the TUI draws them: the
record, its cyan label, the half-block wordmark, and the EQ baseline.

Run: python3 assets/make_art.py
"""

from pathlib import Path

RECORD = [" ▄▀▀▀▄ ", "█     █", " ▀▄▄▄▀ "]
WORD = [
    "█▀▀▀▄ █▀▀▀▄ █▀▀▀▀ ▄▀▀▀▄ █▄ ▄█ █▀▀▀▄ █     █▀▀▀▀",
    "█▄▄▄▀ █▀█▀  █▀▀▀  █▄▄▄█ █ ▀ █ █▀▀▀▄ █     █▀▀▀ ",
    "█     █  ▀▄ █▄▄▄▄ █   █ █   █ █▄▄▄▀ █▄▄▄▄ █▄▄▄▄",
]
LETTER = [row[:5] for row in WORD]  # the wordmark's "p"
EQ = "▁▂▃▅▆▇▆▅▃▂▁▂▃▄▅▆▅▄▃▂▁▂▃▅▇█▇▅▃▂▁▂▃▄▅▄▃▂▁▂▃▅▆▇▆▅▃▂▁▂▃▄▃▂▁▂▃▂"
LEVELS = "▁▂▃▄▅▆▇█"
# The TUI's ramp (LightRed, Red, Yellow, LightYellow, Cyan, LightCyan), tuned
# slightly so neighbours stay distinct on a dark background.
RAMP = ["#ff6b6b", "#e8504f", "#f0b43c", "#ffe27a", "#3cc4d0", "#8be8f0"]
RECORD_FILL, LABEL_FILL, WORD_FILL = "#c9c4c0", "#8be8f0", "#ff6b6b"
BG_TOP, BG_BOTTOM = "#26201f", "#141113"
HERE = Path(__file__).parent


class Canvas:
    """Collects square pixels on a grid of side `px` starting at (x0, y0)."""

    def __init__(self, px, x0, y0):
        self.px, self.x0, self.y0 = px, x0, y0
        self.shapes = []

    def pixel(self, col, row, fill):
        p = self.px
        self.shapes.append(
            f'<rect x="{self.x0 + col * p:.2f}" y="{self.y0 + row * p:.2f}" '
            f'width="{p + 0.3:.2f}" height="{p + 0.3:.2f}" fill="{fill}"/>'
        )

    def glyphs(self, lines, col, fill):
        """Half-block text: each line is two pixel rows."""
        for r, line in enumerate(lines):
            for c, ch in enumerate(line):
                if ch in "█▀":
                    self.pixel(col + c, r * 2, fill)
                if ch in "█▄":
                    self.pixel(col + c, r * 2 + 1, fill)

    def label(self, col, row):
        """The record's dot, centred on the cell at (col, row/2)."""
        p = self.px
        self.shapes.append(
            f'<circle cx="{self.x0 + (col + 0.5) * p:.2f}" cy="{self.y0 + (row + 1) * p:.2f}" '
            f'r="{p * 0.62:.2f}" fill="{LABEL_FILL}"/>'
        )

    def eq(self, pattern, col, bottom_row, width=None):
        """EQ bars (▁..█ = n/8 of a two-pixel cell), bottom-aligned on a row."""
        p = self.px
        width = width or len(pattern)
        bottom = self.y0 + bottom_row * p
        for i in range(width):
            h = (LEVELS.index(pattern[i % len(pattern)]) + 1) / 8 * 2 * p
            colour = RAMP[i * len(RAMP) // width]
            self.shapes.append(
                f'<rect x="{self.x0 + (col + i) * p:.2f}" y="{bottom - h:.2f}" '
                f'width="{p + 0.3:.2f}" height="{h:.2f}" fill="{colour}"/>'
            )


def svg(width, height, body, radius=0):
    clip = f'<rect width="{width}" height="{height}" rx="{radius}"/>'
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" width="{width}" height="{height}">
  <!-- generated by assets/make_art.py from the README logo -->
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="0.35" y2="1">
      <stop offset="0" stop-color="{BG_TOP}"/>
      <stop offset="1" stop-color="{BG_BOTTOM}"/>
    </linearGradient>
    <clipPath id="frame">{clip}</clipPath>
  </defs>
  <g clip-path="url(#frame)" shape-rendering="crispEdges">
    <rect width="{width}" height="{height}" fill="url(#bg)"/>
{body}
  </g>
</svg>
'''


def icon():
    """Square app icon: the record and the wordmark's "p" on the EQ."""
    size, pad, gap = 256, 28, 2
    cols = len(RECORD[0]) + gap + len(LETTER[0])
    rows = 3 * 2 + 1 + 2  # glyphs, a blank pixel row, the EQ cell
    px = (size - 2 * pad) / cols
    c = Canvas(px, (size - cols * px) / 2, (size - rows * px) / 2)
    c.glyphs(RECORD, 0, RECORD_FILL)
    c.glyphs(LETTER, len(RECORD[0]) + gap, WORD_FILL)
    c.eq(EQ, 0, rows, cols)
    c.label(3, 2)
    return svg(size, size, "\n".join("    " + s for s in c.shapes), radius=size * 0.225)


def banner():
    """2:1 banner: the full logo, with the EQ running the whole width. 2:1
    sits well both in the website's 16:9 cards and its 21:8 page banner."""
    width, height, gap = 1600, 800, 3
    cols = len(RECORD[0]) + gap + len(WORD[0])
    px = round(width * 0.7 / cols)
    grid_cols = width // px + 2
    x0 = (width - cols * px) / 2
    logo_top = (height - 9 * px) / 2 - px  # glyph rows + gap + EQ, nudged up
    c = Canvas(px, x0, logo_top)

    # A faint cell grid, like a terminal with nothing on it yet.
    first = -int(x0 // px) - 1
    dots = []
    for gy in range(int(height // px) + 2):
        for gx in range(grid_cols):
            dots.append(
                f'<rect x="{x0 + (first + gx) * px + px / 2 - 1:.1f}" '
                f'y="{logo_top + (gy - int(logo_top // px) - 1) * px + px / 2 - 1:.1f}" '
                f'width="2" height="2" fill="#ffffff" opacity="0.05"/>'
            )

    c.glyphs(RECORD, 0, RECORD_FILL)
    c.glyphs(WORD, len(RECORD[0]) + gap, WORD_FILL)
    c.label(3, 2)
    # The EQ spans the banner edge to edge, under the logo.
    c.eq(EQ, first, 9, grid_cols)

    tagline = (
        f'<text x="{width / 2}" y="{logo_top + 12.4 * px:.1f}" text-anchor="middle" '
        f'font-family="Menlo, monospace" font-size="{px * 1.15:.1f}" fill="#8f877a" '
        f'letter-spacing="1">a terminal music-library manager</text>'
    )
    body = "\n".join("    " + s for s in dots + c.shapes) + "\n    " + tagline
    return svg(width, height, body)


if __name__ == "__main__":
    (HERE / "icon.svg").write_text(icon())
    (HERE / "banner.svg").write_text(banner())
