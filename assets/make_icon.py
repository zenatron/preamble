"""Builds assets/icon.svg from the README's half-block logo.

Each terminal cell is one pixel wide and two tall (a half block is one square
pixel), so the glyphs below are drawn exactly as the TUI draws them: the
record, its cyan label, the first letter of the wordmark, and the EQ baseline.
Run: python3 assets/make_icon.py
"""

RECORD = [" ▄▀▀▀▄ ", "█     █", " ▀▄▄▄▀ "]
LETTER = ["█▀▀▀▄", "█▄▄▄▀", "█    "]  # the wordmark's "p"
EQ = "▁▂▃▅▆▇▆▅▃▂▁▂▃▄"
# The TUI's ramp (LightRed, Red, Yellow, LightYellow, Cyan, LightCyan), tuned
# slightly so neighbours stay distinct on a dark background.
RAMP = ["#ff6b6b", "#e8504f", "#f0b43c", "#ffe27a", "#3cc4d0", "#8be8f0"]
RECORD_FILL, LABEL_FILL, LETTER_FILL = "#c9c4c0", "#8be8f0", "#ff6b6b"
BG_TOP, BG_BOTTOM = "#26201f", "#141113"

GAP = 2  # cells between record and letter, as in the logo
cols = len(RECORD[0]) + GAP + len(LETTER[0])
rows_px = 3 * 2 + 1 + 2  # glyph rows, a blank pixel row, the EQ cell
SIZE, PAD = 256, 28
px = (SIZE - 2 * PAD) / cols
x0 = (SIZE - cols * px) / 2
y0 = (SIZE - rows_px * px) / 2

rects = []

def pixel(cx, py, fill):
    rects.append(
        f'<rect x="{x0 + cx * px:.2f}" y="{y0 + py * px:.2f}" '
        f'width="{px + 0.3:.2f}" height="{px + 0.3:.2f}" fill="{fill}"/>'
    )

def glyphs(lines, col_offset, fill):
    for row, line in enumerate(lines):
        for col, ch in enumerate(line):
            top = ch in "█▀"
            bottom = ch in "█▄"
            if top:
                pixel(col_offset + col, row * 2, fill)
            if bottom:
                pixel(col_offset + col, row * 2 + 1, fill)

glyphs(RECORD, 0, RECORD_FILL)
glyphs(LETTER, len(RECORD[0]) + GAP, LETTER_FILL)

# The label: a filled dot centred in the record's middle cell.
cx = x0 + 3.5 * px
cy = y0 + 3 * px
label = f'<circle cx="{cx:.2f}" cy="{cy:.2f}" r="{px * 0.62:.2f}" fill="{LABEL_FILL}"/>'

# EQ: each ▁..█ fills n/8 of a two-pixel cell, bottom-aligned.
levels = "▁▂▃▄▅▆▇█"
eq_bottom = y0 + rows_px * px
for i, ch in enumerate(EQ[:cols]):
    h = (levels.index(ch) + 1) / 8 * 2 * px
    colour = RAMP[i * len(RAMP) // cols]
    rects.append(
        f'<rect x="{x0 + i * px:.2f}" y="{eq_bottom - h:.2f}" '
        f'width="{px + 0.3:.2f}" height="{h:.2f}" fill="{colour}"/>'
    )

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {SIZE} {SIZE}" width="{SIZE}" height="{SIZE}">
  <!-- preamble app icon, generated by assets/make_icon.py from the README logo. -->
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="0.35" y2="1">
      <stop offset="0" stop-color="{BG_TOP}"/>
      <stop offset="1" stop-color="{BG_BOTTOM}"/>
    </linearGradient>
    <clipPath id="squircle"><rect width="{SIZE}" height="{SIZE}" rx="{SIZE * 0.225}"/></clipPath>
  </defs>
  <g clip-path="url(#squircle)" shape-rendering="crispEdges">
    <rect width="{SIZE}" height="{SIZE}" fill="url(#bg)"/>
    {chr(10).join("    " + r for r in rects).strip()}
  </g>
  {label}
</svg>
'''
open(__file__.replace("make_icon.py", "icon.svg"), "w").write(svg)
